"""Generate the checked-in OpenAPI document and minimal TypeScript DTOs."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from campus.api.main import app
from campus.domain.contracts import PUBLIC_CONTRACTS

ROOT = Path(__file__).resolve().parents[2]
OPENAPI_PATH = ROOT / "backend" / "openapi.json"
TYPES_PATH = ROOT / "packages" / "api-client" / "src" / "generated.ts"


def type_name(reference: str) -> str:
    return reference.rsplit("/", maxsplit=1)[-1]


def type_for(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return type_name(schema["$ref"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "anyOf" in schema:
        return " | ".join(type_for(part) for part in schema["anyOf"])
    schema_type = schema.get("type")
    if schema_type == "array":
        return f"({type_for(schema.get('items', {}))})[]"
    if schema_type == "null":
        return "null"
    if schema_type == "object":
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            return f"Record<string, {type_for(additional)}>"
        return (
            "Record<string, unknown>"
            if additional is not False
            else "Record<string, never>"
        )
    if schema_type == "integer" or schema_type == "number":
        return "number"
    if schema_type == "boolean":
        return "boolean"
    return "string" if schema_type == "string" else "unknown"


def render_types(openapi: dict[str, Any]) -> str:
    components = openapi.get("components", {}).get("schemas", {})
    lines = [
        "/* Generated by backend/scripts/generate_contracts.py. Do not edit. */",
        "",
    ]
    for name, schema in components.items():
        if "enum" in schema:
            lines.append(f"export type {name} = {type_for(schema)};")
            lines.append("")
            continue
        if schema.get("type") != "object":
            lines.append(f"export type {name} = {type_for(schema)};")
            lines.append("")
            continue
        required = set(schema.get("required", []))
        lines.append(f"export interface {name} {{")
        for field_name, field_schema in schema.get("properties", {}).items():
            optional = "" if field_name in required else "?"
            lines.append(f"  {field_name}{optional}: {type_for(field_schema)};")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def generated_files() -> dict[Path, str]:
    openapi = app.openapi()
    schemas = openapi.setdefault("components", {}).setdefault("schemas", {})
    for model in PUBLIC_CONTRACTS:
        schema = model.model_json_schema(
            by_alias=True, ref_template="#/components/schemas/{model}"
        )
        schemas.update(schema.pop("$defs", {}))
        schemas.setdefault(model.__name__, schema)
    openapi_json = (
        json.dumps(openapi, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    )
    return {OPENAPI_PATH: openapi_json, TYPES_PATH: render_types(openapi)}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = generated_files()
    stale = [
        path
        for path, content in files.items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]
    if args.check:
        if stale:
            print("Generated contract files are stale:")
            for path in stale:
                print(path.relative_to(ROOT))
            return 1
        print("Generated contracts are current.")
        return 0
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    print("Generated " + ", ".join(str(path.relative_to(ROOT)) for path in files))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
